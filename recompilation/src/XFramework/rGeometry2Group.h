using size_t = _Sizet;
using u32 = unsigned int;

class rGeometry2Group : public cResource
{
public:
    class MyDTI;
public:
    class MyDTI : public MtDTI
    {
    public:
        MyDTI(MT_CTSTR class_name, MtDTI* ps, size_t size, u32 id, u32 attr);
        virtual MtObject* newInstance() const;  // vtable slot 2
    };
public:
    static MtDTI* getMyDTIPtr();
    static void usage();
    virtual const MtDTI& getDTI() const;  // vtable slot 5
    static MtAllocator* getAllocator();
    static void setAllocator(u32);
    static void* operator new(size_t sz, u32 align);
    static void* operator new[](size_t sz, u32 align);
    static void* operator new(size_t sz, void* p_addr);
    static void* operator new[](size_t sz, void* p_addr);
    static void operator delete(void* p_addr);
    static void operator delete[](void* p_addr);
    static void operator delete(void* p_addr, u32 align);
    static void operator delete[](void* p_addr, u32 align);
    rGeometry2Group();
    virtual ~rGeometry2Group();
    virtual MtUI* createUI(MtProperty& prop);  // vtable slot 2
    virtual void createProperty(MtPropertyList& s);  // vtable slot 4
    virtual void clear();  // vtable slot 15
    virtual bool load(MtStream& in);  // vtable slot 11
    virtual bool save(MtStream& out);  // vtable slot 12
    virtual MT_CTSTR getExt() const;  // vtable slot 7
    rGeometry2* getGeometryResource(u32 ResourceIndex) const;
    u32 getGeometryResourceNum() const;
protected:
    u32 mMagic;  // offset: 0x70
    u32 mVersion;  // offset: 0x74
    MtArray mGeometryResourceArray;  // offset: 0x78
public:
    static MyDTI DTI;
    static const u32 MAGIC = 1735353703;
    static const u32 VERSION = 201030400;
};

inline void* rGeometry2Group::operator new(size_t sz, void* p_addr) {
    return p_addr;
}

